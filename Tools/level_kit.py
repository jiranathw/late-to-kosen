# Things that count toward "traps survived" on the results screen. A bike rack
# is not a hazard and a signpost is not an achievement.
HAZARD_KINDS = {"Trap", "TrapHidden", "TrapSpike", "MonitorLizard", "Flowerpot",
                "TrafficLane", "Floodwater", "Teleporter"}

# Kinds the "is it standing on ground?" rule must skip: these legitimately
# float, span, or sit over a hole by design.
AIRBORNE_KINDS = {"Ground", "Floodwater", "TrafficLane", "Flowerpot",
                  "PlatformFake"}


class Place:
    """One prefab instance. `props` maps 'component.field' -> value, where the
    component key is one of the keys in P[kind] ('mb', 'mb2', ...)."""

    __slots__ = ("kind", "name", "pos", "scale", "props", "note")

    def __init__(self, kind, name, pos, scale=(1, 1, 1), props=None, note=""):
        self.kind = kind
        self.name = name
        self.pos = tuple(pos) if len(pos) == 3 else (pos[0], pos[1], 0)
        self.scale = tuple(scale)
        self.props = props or {}
        self.note = note


# ============================================================================
# CONSTRUCTORS
#
# Every one takes the SURFACE the thing sits on, not the thing's own centre.
# Level tables are written in terms of "on the lobby floor at x=69", and the
# offset from a floor to the middle of the object is a property of the object,
# so it belongs here and not in fifteen call sites.
# ============================================================================

def ground(name, x, y, w, h, flag=""):
    return Place("Ground", name, (x, y), (w, h, 1), note=flag)


def trap(name, x, top):
    # A 0.5u box on the surface: half a unit of a 3.57u arc to clear. Visible,
    # honest, and the thing every later lie is measured against.
    return Place("Trap", name, (x, top + 0.25), (0.5, 0.5, 0.5))


def hidden(name, x, top):
    # A thin floor patch just proud of the surface, so it catches the player
    # however they arrive - walking, landing, or clipping the edge.
    return Place("TrapHidden", name, (x, top + 0.2), (1.2, 0.4, 1))


def kill_floor(name, x, floor_top, w):
    # The same invisible collider, stretched: the plug in a stairwell gap, so
    # missing a jump is a death and not a free ride down to the floor below.
    #
    # TAKES THE TOP OF THE FLOOR IT PLUGS, NOT A CENTRE. It used to be given a
    # y in the middle of the shaft, and that was wrong in a way nobody noticed
    # until it was played: the floors are 5u apart, the slabs are 1u thick, so
    # the headroom between one floor and the underside of the next is 4u - and
    # the apex is 3.11u on top of a 1.0u body. A normal jump anywhere under the
    # block put the player's head straight into it. Void_F1 was the worst: it
    # hung over the main street, so a jump between x=14 and x=17 on the way out
    # of the tower was an instant death for no reason at all.
    #
    # It now fills the slab band instead - floor_top-1.0 up to floor_top-0.1 -
    # and carries onlyKillFromAbove, so a rise from underneath passes through it
    # and only a fall INTO the gap kills.
    #
    # The 0.1u of daylight under the surface is not cosmetic: Fake_01_Doormat
    # sits flush on top of the gap at x=13, and a block whose top touched the
    # walking line would fire the instant the player stepped onto the doormat,
    # killing him before the fake had a chance to drop out from under him. That
    # reads as a bug. Falling in still catches it 0.1u later, which is one
    # frame.
    #
    # Flagged "airborne" because it is the one hazard that is SUPPOSED to hang
    # over a hole - the verifier's "is it standing on ground?" rule would
    # otherwise reject every one of them.
    return Place("TrapHidden", name, (x, floor_top - 0.55), (w, 0.9, 1),
                 {"mb.onlyKillFromAbove": 1}, note="airborne")


def spike(name, x, top):
    # Rests fully inside the platform. SpikeTrap lifts it 1.1u, clearing the
    # surface by 0.1u - visible, but only a few frames early.
    return Place("TrapSpike", name, (x, top - 0.5), (0.8, 1, 1))


def fake(name, x, top, w=2.0):
    return Place("PlatformFake", name, (x, top - 0.5), (w, 1, 1))


def checkpoint(name, x, top):
    # The respawn position IS this transform, so it sits high enough that the
    # player materialises just above the surface rather than inside it.
    return Place("Checkpoint", name, (x, top + 0.6))


def goal(name, x, top):
    # 2x3 doorway: impossible to miss, and it reads as a door and not a coin.
    return Place("Goal", name, (x, top + 1.5), (2, 3, 1))


def sign(name, x, top, message, latch=False, show=5.5):
    return Place("Signpost", name, (x, top + 0.7), (0.25, 1.4, 1),
                 {"mb.message": message, "mb.showRange": show,
                  "mb.latch": 1 if latch else 0})


def fake_goal(name, x, top, reveal, penalty, sign_text):
    return Place("FakeGoal", name, (x, top + 1.5), (2, 3, 1),
                 {"mb.revealText": reveal, "mb.timePenalty": penalty,
                  "mb2.message": sign_text, "mb2.showRange": 6})


def bicycle(name, x, top, offer=None):
    # Not a boost. Touching one starts a ride only a real rack can end, so a
    # bike has to be placed like a decision: visible early enough to refuse,
    # and never on the only route.
    props = {}
    if offer:
        props["mb.offerMessage"] = offer
    return Place("Bicycle", name, (x, top + 0.95), (0.9, 0.9, 1), props)


def bike_rack(name, x, top, real=True, refused=None, cost=0.0):
    """A place to end the ride, or a convincing photograph of one.

    Real and fake racks are the same prefab, the same size and the same sign,
    and the only difference is one boolean. A fake the player can spot is not
    a fake, it is a warning.
    """
    props = {"mb.isReal": 1 if real else 0}
    if refused:
        props["mb.refusedMessage"] = refused
    if cost:
        props["mb.refusalTimeCost"] = cost
    return Place("BikeRack", name, (x, top + 0.6), (2.6, 1.2, 1), props)


def lizard(name, x, top, chase=7.0, give_up=24.0, trigger=8.0):
    # Was the soi dog. A monitor lizard is what actually comes out of a Lat
    # Krabang klong in the morning, and it is funnier because it is true.
    #
    # chase < WALK_SPEED on purpose: it is a fright, not a wall. On a bike it
    # is nothing, which is the first time the bike pays for itself.
    return Place("MonitorLizard", name, (x, top + 0.35), (1.9, 0.7, 1),
                 {"mb.chaseSpeed": chase, "mb.giveUpDistance": give_up,
                  "mb.triggerDistance": trigger})


def chaser(name, x, top, chase, give_up, trigger=10.0, wind_up=0.6,
           size=(1.0, 1.9), color=(0.32, 0.34, 0.40)):
    """The same ChaserHazard as the lizard, wearing a shirt.

    Stage 1's bike section is gated by this and by nothing else. A chaser at
    9.0 against a 7.5 walk closes 1.5u/s, so the wind-up head start is spent in
    about three seconds and a walker dies in the middle of the corridor; the
    same chaser against an 11.25 ride loses 2.25u/s and is never a threat. That
    difference IS the gate - no key, no script, no rule to explain - and it is
    why the corridor has to be long enough for the arithmetic to finish.

    Sized 1.0 x 1.9 rather than the lizard's 1.9 x 0.7, so the silhouette reads
    as a person from across the screen even before Bun's teacher_1.png is on it.
    """
    return Place("MonitorLizard", name, (x, top + size[1] / 2.0),
                 (size[0], size[1], 1),
                 {"mb.chaseSpeed": chase, "mb.giveUpDistance": give_up,
                  "mb.triggerDistance": trigger, "mb.windUpSeconds": wind_up,
                  "sr.m_Color.r": color[0], "sr.m_Color.g": color[1],
                  "sr.m_Color.b": color[2], "sr.m_Color.a": 1})


def pot(name, x, y, trigger=3.4):
    return Place("Flowerpot", name, (x, y), (0.7, 0.7, 1),
                 {"mb.triggerDistance": trigger})


def boulder(name, x, y, w, h, trigger=4.0):
    # A flowerpot the size of a car. Krin has one of these hanging over his
    # arena with no script on it at all - it never falls, and the whole point
    # is that you do not find that out until you have already run past it.
    return Place("Flowerpot", name, (x, y), (w, h, 1),
                 {"mb.triggerDistance": trigger})


def lane(name, x, y, length, speed, every, delay, size, color):
    return Place("TrafficLane", name, (x, y), (1, 1, 1),
                 {"mb.laneLength": length, "mb.speed": speed,
                  "mb.spawnEverySeconds": every, "mb.firstSpawnDelay": delay,
                  "mb.vehicleSize.x": size[0], "mb.vehicleSize.y": size[1],
                  "mb.vehicleColor.r": color[0], "mb.vehicleColor.g": color[1],
                  "mb.vehicleColor.b": color[2], "mb.vehicleColor.a": 1,
                  "mb.activationRange": length * 0.5 + 14})


def water(name, x, y, size, rise, max_height, trigger_x):
    return Place("Floodwater", name, (x, y), (1, 1, 1),
                 {"mb.riseSpeed": rise, "mb.maxHeight": max_height,
                  "mb.triggerAtPlayerX": trigger_x,
                  "mb.surfaceSize.x": size[0], "mb.surfaceSize.y": size[1]})


def teleporter(name, x, top, dest_x, dest_y, move_checkpoint=True):
    return Place("Teleporter", name, (x, top + 1.5), (1.6, 3, 1),
                 {"mb.destination.x": dest_x, "mb.destination.y": dest_y,
                  "mb.moveCheckpointToExit": 1 if move_checkpoint else 0,
                  "mb.oneShot": 1})
