"""Shared vocabulary for the level generators.

Tools/build_levels.py used to hold all of this plus both level tables, and it
grew to 900 lines. Splitting it was not tidiness: a file that size is awkward
to review, and every level edit produced a diff against the emitter and the
verifier as well. Now the layout tables live in Tools/stage1.py and
Tools/stage2.py, the machinery lives in Tools/build_levels.py, and this module
is the only thing all three share.

Nothing here writes a file. It defines the player's physics, the prefab table,
and one small constructor per kind of thing a level can contain, so a stage
file reads as a list of decisions rather than a list of coordinates.
"""

# ============================================================================
# PHYSICS
#
# These four numbers are the game. Everything else in this file is measured
# against them, and they exist in four places that must agree:
#     Assets/Scenes/Level1.unity           (what actually runs - the scene's
#                                           serialised fields win over the C#
#                                           defaults, so this one is not
#                                           optional)
#     Assets/Scripts/PlayerController.cs   (moveSpeed, jumpForce, fall/low mult)
#     Tools/scene_skeleton.unity           (m_GravityScale, and the same fields)
#     here                                 (what the verifier checks layouts on)
#
# Level2.unity is deliberately NOT in that list. Krin's scene carries his own
# tuning - jumpForce 7 at gravityScale 1, moveSpeed 6 - and it is adopted, not
# built, so nothing here reaches it and nothing here should.
#
# Retuned on the evening of 28 Aug. Sprint was removed and its speed became the only speed, and
# the jump was rebuilt around Krin's stage - see the module docstring in
# Tools/stage2.py for why his level forced this.
#
# Lowered 13.5 -> 12.6 on 30 Aug: the arc was clearing scenery it was never
# meant to clear (the shaft walls, the kerb) and it read as a moon jump. Apex
# 3.57 -> 3.11, reach 6.93 -> 6.47. What stops it going lower is stage 1's own
# dismount gate: the kerb has to be walkable at 70% of the apex and unreachable
# on a bike, and at 12.6 that window is 2.05u wide with 0.16u of slack. Below
# about 12.0 the window closes and the bike section loses its exit.
# ============================================================================
GRAVITY = 9.81
JUMP_FORCE = 12.6
GRAVITY_SCALE = 2.6
FALL_MULTIPLIER = 1.8
WALK_SPEED = 7.5

# Riding is faster and jumps lower. Both matter: the extra speed means a rider
# clears every gap a walker can, but the lower arc means a step-up a walker
# finds trivial can be impossible on a bike - and the bike cannot be dropped
# except at a rack. Any stretch a rider can still be on has to be checked
# against BOTH sets of numbers or the level can softlock.
BIKE_SPEED_MULTIPLIER = 1.5
BIKE_JUMP_MULTIPLIER = 0.78

# A gap may use at most this fraction of the arc that clears it. The missing
# quarter is the difference between "the arithmetic works" and "a person who
# has not memorised this jump lands it".
GAP_SAFETY = 0.75

# A step-up may use at most this fraction of the apex. Higher than it looks:
# 0.70 is what Krin's stage needs, because his +2.32u climb out of the arena is
# 65% of ours. Anything above ~0.55 gets a warning, because a tall step has to
# be taken near the top of the arc where there is very little room left.
STEP_APEX = 0.70
STEP_APEX_WARN = 0.55


def jump_apex(riding=False):
    j = JUMP_FORCE * (BIKE_JUMP_MULTIPLIER if riding else 1.0)
    return j ** 2 / (2.0 * GRAVITY * GRAVITY_SCALE)


def horizontal_reach(step_up, riding=False):
    """Max horizontal distance from take-off to landing `step_up` units higher.

    Rise and fall use different gravity, so this is two parabolas stitched at
    the apex, not one symmetric arc. Returns 0 if the step is higher than the
    jump reaches at all.
    """
    j = JUMP_FORCE * (BIKE_JUMP_MULTIPLIER if riding else 1.0)
    v = WALK_SPEED * (BIKE_SPEED_MULTIPLIER if riding else 1.0)
    g_up = GRAVITY * GRAVITY_SCALE
    g_down = g_up * FALL_MULTIPLIER
    apex = jump_apex(riding)
    if step_up >= apex:
        return 0.0
    t_rise = j / g_up
    t_fall = (2.0 * (apex - step_up) / g_down) ** 0.5
    return v * (t_rise + t_fall)


